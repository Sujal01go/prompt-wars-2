import type { DailySmogRoutine, AirQualityTelemetry, PersonaProfile } from '../types/index.ts'

/**
 * Generates formatted Markdown report of the daily smog routine
 */
export function formatRoutineMarkdown(
  routine: DailySmogRoutine,
  persona: PersonaProfile,
  telemetry: AirQualityTelemetry
): string {
  const lines: string[] = []

  lines.push(`# 🌬️ AeroPulse AI — Daily Smog Defense Protocol`)
  lines.push(`**Date**: ${routine.date} | **Location**: ${routine.city}`)
  lines.push(`**Target Persona**: ${persona.name} (${persona.vulnerabilityLevel} Vulnerability)`)
  lines.push(`**Current AQI**: ${telemetry.aqi} (${telemetry.categoryLabel}) | **Dominant Pollutant**: ${telemetry.dominantPollutant.toUpperCase()} (${telemetry.pm25} µg/m³)`)
  lines.push(`**Golden Ventilation Window**: ${routine.goldenVentilationWindow}`)
  lines.push(`\n---\n`)

  lines.push(`## 🕒 Hour-by-Hour Routine & Smog Mitigation Plan\n`)
  for (const step of routine.steps) {
    const maskText = step.maskRequired ? '😷 N95/FFP2 Mask Required' : '✅ Mask Optional'
    lines.push(`### [${step.time}] ${step.title}`)
    lines.push(`- **Period**: ${step.period} | **Location**: ${step.locationType.toUpperCase()} | **Mask**: ${maskText}`)
    lines.push(`- **Action**: ${step.action}`)
    lines.push(`- **Clinical Guidance**: ${step.guidance}\n`)
  }

  lines.push(`## 🏠 Indoor Air Quality (IAQ) Checklist`)
  for (const item of routine.iaqChecklist) {
    lines.push(`- [ ] ${item}`)
  }

  lines.push(`\n## 🥗 Dietary & Antioxidant Protection`)
  for (const diet of routine.dietaryAntioxidants) {
    lines.push(`- ${diet}`)
  }

  lines.push(`\n---\n*Generated by AeroPulse AI — Urban Air Quality & Smog Defense Assistant*`)
  return lines.join('\n')
}

/**
 * Triggers browser download of text file
 */
export function downloadTextFile(filename: string, content: string, mimeType = 'text/markdown'): void {
  const blob = new Blob([content], { type: mimeType })
  const url = URL.createObjectURL(blob)
  const a = document.createElement('a')
  a.href = url
  a.download = filename
  document.body.appendChild(a)
  a.click()
  document.body.removeChild(a)
  URL.revokeObjectURL(url)
}

/**
 * Exports telemetry data to CSV
 */
export function exportTelemetryToCsv(
  telemetry: AirQualityTelemetry,
  city: string
): void {
  const headers = ['Parameter', 'Value', 'Unit', 'WHO Standard', 'Status']
  const rows: string[][] = [
    ['Location', city, '', '', ''],
    ['Timestamp', telemetry.timestamp, '', '', ''],
    ['US AQI', telemetry.aqi.toString(), 'Index', '0-50', telemetry.categoryLabel],
    ['PM2.5', telemetry.pm25.toString(), 'µg/m³', '15', telemetry.pollutants.pm25?.status || ''],
    ['PM10', telemetry.pm10.toString(), 'µg/m³', '45', telemetry.pollutants.pm10?.status || ''],
    ['NO2', telemetry.no2.toString(), 'µg/m³', '25', telemetry.pollutants.no2?.status || ''],
    ['SO2', telemetry.so2.toString(), 'µg/m³', '40', telemetry.pollutants.so2?.status || ''],
    ['Ozone (O3)', telemetry.o3.toString(), 'µg/m³', '100', telemetry.pollutants.o3?.status || ''],
    ['Carbon Monoxide (CO)', telemetry.co.toString(), 'mg/m³', '4', telemetry.pollutants.co?.status || ''],
    ['Temperature', telemetry.temperature.toString(), '°C', '', ''],
    ['Humidity', telemetry.humidity.toString(), '%', '', ''],
    ['Wind Speed', telemetry.windSpeed.toString(), 'km/h', '', ''],
    ['Inversion Stagnation Index', telemetry.stagnationIndex.toString(), '/100', '', telemetry.inversionRisk],
  ]

  const csvContent = [
    headers.join(','),
    ...rows.map((row) => row.map((cell) => `"${cell.replace(/"/g, '""')}"`).join(',')),
  ].join('\n')

  downloadTextFile(`AeroPulse-Telemetry-${city.replace(/\s+/g, '_')}.csv`, csvContent, 'text/csv')
}
